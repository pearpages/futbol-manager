/**
 * Every `given surname` combination, in a fixed order. ~70 × 73 ≈ 5,100 names —
 * comfortably more than the ~460 a league needs, so a season can fill twenty
 * squads without repeating.
 *
 * The order is deterministic and load-bearing: generation indexes into this list,
 * so reordering it renames every player in every existing save.
 */
export const PLAYER_NAMES: readonly string[] = GIVEN_NAMES.flatMap((given) =>
  SURNAMES.map((surname) => `${given} ${surname}`),
)
