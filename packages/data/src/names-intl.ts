/**
 * Name pools for players abroad.
 *
 * **These no longer name the opening squads** — `foreign-rosters.ts` does, with
 * real shapes and altered surnames, per
 * [ADR 0011](../../../docs/adr/0011-a-market-abroad.md). What they still name is
 * **everyone who arrives afterwards**: the replacements `refreshForeignLeague`
 * signs at every rollover. That is deliberate and it is the same arrangement
 * `PLAYER_NAMES` has at home — a career drifts off the shipped squads on its own.
 *
 * It is also a hard requirement rather than a preference. `refreshForeignLeague`
 * generates a whole squad as a recruit pool; handed the roster it would re-issue
 * names already on that club's books, and the duplicate-name guard only inspects
 * the roster files, so it would go unnoticed.
 *
 * Ordinary common given names and surnames of each country, combined by the
 * generator. Roughly 30 × 30 per country gives ~900 combinations against the ~22
 * a club needs, so a league fills without repeating.
 *
 * **The order is deterministic and load-bearing**, exactly as `PLAYER_NAMES` is:
 * generation indexes into these lists, so reordering one renames every foreign
 * player generated in every existing save.
 */

