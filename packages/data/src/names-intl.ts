/**
 * Every `given surname` combination per country, in a fixed order.
 *
 * Shaped as one flat pool per country because that is what `generateSquad` takes —
 * it indexes into `options.names` and knows nothing about where a club is.
 */
/**
 * Both lists advance together, rather than one nesting inside the other.
 *
 * **`given.flatMap(surnames)` is the wrong order for a sequential consumer**, and
 * it shipped for exactly as long as it took to look at a squad: `generateSquad`
 * indexes 0, 1, 2… so a club got the first twenty-three entries, which under that
 * nesting share one given name. München fielded twenty-three men called Andreas.
 *
 * Walking a diagonal through the grid makes consecutive entries differ in both
 * halves. The strides are **coprime with 30**, which is what guarantees each index
 * still visits every name before repeating — and it is also what stops a squad
 * reading like a dictionary: stepping by one gave München an Aumann, a Bergmann, a
 * Brandt and a Dietrich in that order, alphabetical down the whole team sheet.
 *
 * The same latent trap exists in `PLAYER_NAMES`, which is built the nested way —
 * it is invisible only because the twenty domestic squads come from real rosters
 * and everyone generated afterwards is drawn at a random index. Reordering it
 * would rename every player in every existing save, so it is left alone; anything
 * new that indexes it sequentially should come here first.
 */
/** Coprime with 30, so each list still visits every entry before repeating. */
const GIVEN_STRIDE = 11
const SURNAME_STRIDE = 7

const combine = (country: Country): readonly string[] => {
  const given = GIVEN[country]
  const surnames = SURNAMES[country]
  return Array.from(
    { length: given.length * surnames.length },
    (_, i) =>
      `${given[(i * GIVEN_STRIDE) % given.length] ?? ''} ${surnames[(i * SURNAME_STRIDE + Math.floor(i / given.length)) % surnames.length] ?? ''}`,
  )
}

export const INTL_NAMES: Readonly<Record<Country, readonly string[]>> = {
  EN: combine('EN'),
  DE: combine('DE'),
  FR: combine('FR'),
  IT: combine('IT'),
  PT: combine('PT'),
  NL: combine('NL'),
  BE: combine('BE'),
  TR: combine('TR'),
}
