/**
 * Opening squads for the twenty clubs, shaped on real ones.
 *
 * **Where this comes from, and what was changed.** Positions, ages and the value
 * curve inside each squad are taken from real rosters; **every surname is altered**.
 * That overrides ADR 0007's fourth decision, which required generated names — the
 * change is recorded in [ADR 0010](../../../docs/adr/0010-real-squad-shapes.md),
 * including the exposure it accepts. Given names are ordinary Spanish given names
 * and are kept as they are; a given name identifies nobody on its own.
 *
 * **Refreshed in October 2026, after the summer window** (ADR 0024), from
 * Wikipedia's squad lists, which are CC BY-SA 4.0 (attribution: the English
 * Wikipedia articles of each club and its 2026–27 season). A player still at his
 * club kept his row; one who moved between two of these clubs took his row with
 * him; a newcomer got an altered surname, his age at the season start, and his
 * club's median `value` for his position, since Wikipedia carries no market
 * values.
 *
 * **The alteration was applied once, offline, and only its output is here.** A
 * mutation function shipped alongside the real list would put the real surnames in
 * the repository, which is the thing the alteration exists to avoid — so there is no
 * such function in the codebase and this file is the only artefact.
 *
 * **`value` shapes a squad, and it is not a price.** It is the market value the squad
 * was shaped from, in thousands, and generation reads its **magnitude** — how far a
 * player sits below his club's best, measured against what a player at his position
 * normally costs. It was once only a sort key, which is what made every squad in the
 * league the same ten-point block with Madrid's worst player an 81.
 *
 * Absolute quality still comes from the club rating, because `calibrateSquad` collapses
 * every squad back onto `attack`/`defence` regardless of what is in here. Wages and
 * asking prices are priced by `valuation.ts` from the finished attributes and never
 * from this column. **Do not start reading it as a transfer fee.**
 *
 * **`position` is the game's four, not the source's fifteen.** Centre-backs and
 * full-backs are defenders, holding and attacking midfielders are midfielders. Wingers
 * are the interesting case: they are exactly the players who fill either a wide
 * midfield slot or a place in a front three, so they were assigned to whichever bank
 * their squad was short of. No fixed mapping works — 3-5-2 and 4-5-1 want five
 * midfielders, 4-3-3 and 3-4-3 want three forwards, 4-2-4 wants four, and in the source
 * data Barcelona has nobody listed as a striker at all while Sevilla and Vigo have only
 * four central midfielders.
 *
 * **The counts below were solved offline against the formations that existed then, and
 * they are frozen.** Adding a formation does not rebalance them — it tightens a
 * constraint the data was already solved for. After the October refresh Vigo and
 * Getafe sit at exactly five midfielders, the binding corner, not headroom.
 *
 * Squad sizes are the real ones, 22 to 30, rather than the generator's flat 23. They
 * sit inside `MIN_SQUAD` and `MAX_SQUAD`, and every one satisfies the positional
 * minimum of every formation — there is a test for that, because a squad that cannot
 * field a shape would throw out of `bestXI` rather than fail politely.
 *
 * Clubs outside the league carry no roster: nothing generates squads for them.
 *
 * `[name, position, age, value]` — a tuple for the same reason `CLUBS` uses one:
 * five hundred rows of object literals is unreadable, and the shape is fixed.
 */
