/**
 * Groups the scanned runs by ink, in `COVER_INK_KEYS` order.
 *
 * Flat — one level, no parts. The hub figures need a second axis because a prop
 * animates independently of the body; nothing here moves.
 */
export function decodeCover(rows: readonly string[]): DecodedCover {
  const { width, height } = gridSize(rows)
  const byInk = new Map<CoverInk, CoverRun[]>()

  for (const run of scanRuns(rows)) {
    const ink = COVER_INK_BY_CHAR[run.char]
    // Unknown characters are skipped rather than thrown on, the way every other
    // decoder here behaves. A typo loses a pixel; it does not lose the page.
    if (ink === undefined) continue
    const into = byInk.get(ink) ?? []
    into.push({ x: run.x, y: run.y, w: run.w })
    byInk.set(ink, into)
  }

  const inks: CoverInkRuns[] = []
  for (const ink of COVER_INK_KEYS) {
    const runs = byInk.get(ink)
    if (runs !== undefined) inks.push({ ink, runs })
  }
  return { width, height, inks }
}

export const COVER = decodeCover(COVER_GRID)
