/**
 * The cover: a manager on the touchline at night, looking out over a floodlit
 * pitch. 161 x 91, one flat grid, one character per pixel.
 *
 * **Odd in both axes**, like `stadium-plan.ts` and for the same reason — the view
 * is symmetric about the goal, so that axis has to be a real pixel rather than a
 * seam. The pitch markings are mirrored about column 80 and there is a test for
 * it, because a pitch drawn one column off-centre is invisible in source.
 *
 * **One grid, not modules.** The stadium is moduled so a ghosted tier never
 * paints over a built one; a cover has no tiers and no state, so the disjointness
 * invariant would be ceremony. And splitting it into bands would hide the thing
 * that most needed tuning: the seams *between* the bands. Full bleed, so it abuts
 * sky-to-roof-to-crowd-to-pitch-to-foreground with nothing between, and a hard
 * dark divider at every one of those joins is what stops two bands reading as a
 * single slab of concrete — the failure `stadium-plan.ts` had to be redrawn for.
 *
 * **Club-agnostic, and that is structural rather than stylistic.** `stadium.css`
 * takes its seats from `var(--badge-a)` through `data-colours`, but this renders
 * on the landing page, *before a club exists* — that is the whole point of a
 * landing page — so `badgeFor` has nothing to give it. Its palette is its own,
 * and a test asserts `cover.css` never reaches for a badge token.
 *
 * The geometry was laid down by a throwaway generator and the output pasted here
 * as literal rows, which is exactly what `stadium-plan.ts` did with its
 * concentric maths: a vanishing point and an ellipse are not things to place by
 * eye at this size. The generator is gone. Everything after it — the seams, the
 * lamp banks, the rim light, the lettering — was tuned by hand here.
 */

